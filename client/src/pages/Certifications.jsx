import React, { useState, useEffect } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { 
  Award, Shield, Calendar, Loader2, CheckCircle2, 
  HelpCircle, Check, X, FileText, Search, ExternalLink 
} from 'lucide-react';
import toast from 'react-hot-toast';
import axios from 'axios';

const Certifications = () => {
  const [certs, setCerts] = useState([]);
  const [bookings, setBookings] = useState([]);
  const [loading, setLoading] = useState(true);
  const [bookingId, setBookingId] = useState(null);

  // Exam simulator states
  const [activeBooking, setActiveBooking] = useState(null);
  const [currentQuestions, setCurrentQuestions] = useState([]);
  const [currentAnswers, setCurrentAnswers] = useState({});
  const [grading, setGrading] = useState(false);
  const [examResult, setExamResult] = useState(null);

  // Verifier states
  const [searchQrCode, setSearchQrCode] = useState('');
  const [verifying, setVerifying] = useState(false);
  const [verifiedCert, setVerifiedCert] = useState(null);

  useEffect(() => {
    fetchCertificationsAndProfile();
  }, []);

  const fetchCertificationsAndProfile = async () => {
    try {
      setLoading(true);
      const token = localStorage.getItem('token');

      // Fetch certifications
      const certsRes = await axios.get('http://localhost:5000/api/certifications');
      let certData = certsRes.data.data;

      // Seed certifications if empty
      if (certData.length === 0) {
        const mockCerts = [
          {
            title: 'Certified Leasing Professional (CLP)',
            code: 'CLP',
            description: 'Foundation accreditation program verifying knowledge of lease structures, classification metrics, risk evaluation, and legal compliance.',
            price: 150000,
            examDurationMinutes: 30,
            passingScore: 66,
            examQuestions: [
              {
                questionText: 'Under the Nigerian Equipment Leasing Act, which body is empowered to manage registration?',
                options: ['Corporate Affairs Commission (CAC)', 'Equipment Leasing Registration Authority (ELRA)', 'Federal Inland Revenue Service (FIRS)', 'Central Bank of Nigeria (CBN)'],
                correctAnswerIndex: 1
              },
              {
                questionText: 'Which leasing classification transfers substantially all risks and rewards of ownership to the lessee?',
                options: ['Operating Lease', 'Hire Purchase', 'Finance Lease', 'Leveraged Lease'],
                correctAnswerIndex: 2
              },
              {
                questionText: 'What is the primary indicator of a transaction being structured as a lease rather than a loan?',
                options: ['Ownership remains with lessor', 'Lessee pays interest only', 'Collateral is double valued', 'Fixed maturity period'],
                correctAnswerIndex: 0
              }
            ]
          },
          {
            title: 'Certified Leasing & Asset Finance Professional (CLAFP)',
            code: 'CLAFP',
            description: 'Advanced accreditation covering portfolio modeling, asset securitization structures, legal disputes resolutions, and international lease taxation.',
            price: 250000,
            examDurationMinutes: 45,
            passingScore: 66,
            examQuestions: [
              {
                questionText: 'Which metrics calculates the net return generated by a lessor after accounting for tax depreciation?',
                options: ['Internal Rate of Return (IRR)', 'After-Tax Yield', 'Gross Booking Value', 'Debt Service Coverage Ratio'],
                correctAnswerIndex: 1
              },
              {
                questionText: 'In cross-border leasing, what primary risk is mitigated using double tax treaty networks?',
                options: ['Exchange Rate Fluctuation', 'Withholding Tax Exposure', 'Asset Repossession Delay', 'Sovereign Debt Default'],
                correctAnswerIndex: 1
              },
              {
                questionText: 'What legal document grants a lessor repossession rights on default in Nigeria?',
                options: ['Lease Agreement Repossession Clause', 'ELRA Registry Writ', 'CAC Debenture Certificate', 'Court Injunction Decree'],
                correctAnswerIndex: 0
              }
            ]
          }
        ];

        for (const mock of mockCerts) {
          await axios.post('http://localhost:5000/api/certifications', mock, {
            headers: { Authorization: `Bearer ${token}` }
          });
        }

        const refreshedRes = await axios.get('http://localhost:5000/api/certifications');
        certData = refreshedRes.data.data;
      }

      setCerts(certData);

      // Fetch user profile/bookings
      const profileRes = await axios.get('http://localhost:5000/api/profiles/me', {
        headers: { Authorization: `Bearer ${token}` }
      });
      // We can also assume there is a mock booking fetch or fetch from profile certificates.
      // For this prototype, we will simulate bookings state by checking user active credentials.
    } catch (err) {
      console.error(err);
      toast.error('Failed to load certification details');
    } finally {
      setLoading(false);
    }
  };

  const handleBookExam = async (certId) => {
    try {
      setBookingId(certId);
      const token = localStorage.getItem('token');
      const res = await axios.post('http://localhost:5000/api/certifications/book', {
        certificationId: certId,
        bookingDate: new Date()
      }, {
        headers: { Authorization: `Bearer ${token}` }
      });

      if (res.data.success) {
        toast.success(res.data.message || 'Exam booking successful!');
        setBookings([...bookings, res.data.data]);
      }
    } catch (err) {
      console.error(err);
      toast.error('Booking failed');
    } finally {
      setBookingId(null);
    }
  };

  const startExam = (booking) => {
    const matchedCert = certs.find(c => c._id === booking.certification);
    if (!matchedCert) return;
    setActiveBooking(booking);
    setCurrentQuestions(matchedCert.examQuestions);
    setCurrentAnswers({});
    setExamResult(null);
  };

  const handleAnswerSelect = (questionIndex, optionIndex) => {
    setCurrentAnswers({
      ...currentAnswers,
      [questionIndex]: optionIndex
    });
  };

  const handleSubmitExam = async (e) => {
    e.preventDefault();
    if (Object.keys(currentAnswers).length < currentQuestions.length) {
      return toast.error('Please answer all questions before submitting');
    }

    try {
      setGrading(true);
      const token = localStorage.getItem('token');
      const payload = {
        bookingId: activeBooking._id,
        answers: Object.values(currentAnswers)
      };

      const res = await axios.post('http://localhost:5000/api/certifications/submit-exam', payload, {
        headers: { Authorization: `Bearer ${token}` }
      });

      if (res.data.success) {
        setExamResult(res.data);
        // Remove completed booking from active bookings
        setBookings(bookings.filter(b => b._id !== activeBooking._id));
      }
    } catch (err) {
      console.error(err);
      toast.error('Exam evaluation failed');
    } finally {
      setGrading(false);
    }
  };

  const handleVerifyCredential = async (e) => {
    e.preventDefault();
    if (!searchQrCode.trim()) return;

    try {
      setVerifying(true);
      setVerifiedCert(null);
      const res = await axios.get(`http://localhost:5000/api/certifications/verify/${searchQrCode.trim()}`);
      if (res.data.success) {
        setVerifiedCert(res.data.credential);
        toast.success('Credential verified successfully!');
      }
    } catch (err) {
      console.error(err);
      toast.error('Invalid or expired certification credential code');
    } finally {
      setVerifying(false);
    }
  };

  if (loading) {
    return (
      <div className="flex h-[60vh] items-center justify-center">
        <Loader2 className="animate-spin text-primary" size={48} />
      </div>
    );
  }

  return (
    <div className="space-y-8 animate-fade-in text-slate-100 pb-12">
      {/* Title */}
      <div className="space-y-1">
        <h1 className="text-3xl font-extrabold tracking-tight">Professional Certification Centre</h1>
        <p className="text-slate-400">Sit for industry-standard examinations directly and earn verified digital credentials with secure QR codes.</p>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-8">
        {/* Main Cert Options (2 columns) */}
        <div className="lg:col-span-2 space-y-8">
          {/* Active Bookings / Exam Invites */}
          {bookings.length > 0 && (
            <div className="glass p-8 rounded-[2rem] border border-white/5 space-y-6 shadow-xl bg-gradient-to-r from-primary/10 to-purple-950/20">
              <h3 className="text-xl font-bold flex items-center gap-2">
                <Calendar className="text-primary" size={20} /> Scheduled Assessments
              </h3>
              <div className="space-y-4">
                {bookings.map((booking) => {
                  const cert = certs.find(c => c._id === booking.certification);
                  return (
                    <div key={booking._id} className="flex flex-col md:flex-row items-start md:items-center justify-between p-5 bg-slate-950 rounded-2xl border border-white/5 gap-4">
                      <div>
                        <h4 className="font-bold text-white text-base">{cert?.title}</h4>
                        <p className="text-xs text-slate-500 font-medium">Booked: {new Date(booking.bookingDate).toLocaleDateString()}</p>
                      </div>
                      <button
                        onClick={() => startExam(booking)}
                        className="bg-primary hover:bg-primary-hover text-white px-6 py-2.5 rounded-xl font-bold text-xs shadow-lg transition-all"
                      >
                        Start Assessment
                      </button>
                    </div>
                  );
                })}
              </div>
            </div>
          )}

          {/* Exam Catalog */}
          <div className="space-y-6">
            <h3 className="text-xl font-bold flex items-center gap-2">
              <Award className="text-primary" size={20} /> Certification Programs
            </h3>
            <div className="grid grid-cols-1 gap-6">
              {certs.map((cert) => (
                <div key={cert._id} className="glass p-8 rounded-[2.2rem] border border-white/5 flex flex-col md:flex-row md:items-center justify-between gap-6 shadow-xl relative hover:border-white/10 transition-all group">
                  <div className="space-y-4 flex-1">
                    <div className="flex items-center gap-3">
                      <span className="bg-primary/20 text-primary border border-primary/20 text-[10px] font-bold px-2.5 py-1 rounded-full">
                        {cert.code}
                      </span>
                      <h4 className="font-extrabold text-white text-lg group-hover:text-primary transition-colors">{cert.title}</h4>
                    </div>
                    <p className="text-sm text-slate-400 font-medium leading-relaxed">{cert.description}</p>
                    <div className="flex gap-6 text-xs text-slate-500 font-semibold">
                      <span>Passing Score: <strong className="text-slate-300">{cert.passingScore}%</strong></span>
                      <span>Duration: <strong className="text-slate-300">{cert.examDurationMinutes} mins</strong></span>
                    </div>
                  </div>
                  <div className="text-left md:text-right shrink-0 space-y-3">
                    <div className="text-xl font-black text-white">
                      ₦{cert.price.toLocaleString()}
                    </div>
                    <button
                      onClick={() => handleBookExam(cert._id)}
                      disabled={bookingId === cert._id}
                      className="bg-white/5 border border-white/10 hover:bg-primary hover:border-primary text-white px-6 py-3 rounded-2xl font-bold text-xs transition-all shadow-md flex items-center gap-1.5"
                    >
                      {bookingId === cert._id ? <Loader2 className="animate-spin" size={14} /> : <Calendar size={14} />}
                      Book Assessment
                    </button>
                  </div>
                </div>
              ))}
            </div>
          </div>
        </div>

        {/* Public Verifier Panel (1 column) */}
        <div className="space-y-8">
          <div className="glass p-8 rounded-[2rem] border border-white/5 space-y-6 shadow-xl">
            <h3 className="text-xl font-bold flex items-center gap-2">
              <Shield className="text-primary" size={20} /> Public Credential Verifier
            </h3>
            <p className="text-sm text-slate-400">
              Enter any CareerMAX credential verification code or scan a certificate QR code to validate registration authenticity.
            </p>
            <form onSubmit={handleVerifyCredential} className="space-y-4">
              <div className="relative flex items-center">
                <Search size={18} className="absolute left-4 text-slate-500" />
                <input
                  type="text"
                  placeholder="Enter Verification Code..."
                  value={searchQrCode}
                  onChange={(e) => setSearchQrCode(e.target.value)}
                  className="w-full pl-12 pr-4 py-3 bg-slate-950 border border-white/10 rounded-2xl text-white outline-none focus:border-primary transition-all text-sm font-semibold"
                />
              </div>
              <button
                type="submit"
                disabled={verifying}
                className="w-full bg-primary hover:bg-primary-hover text-white py-3 px-4 rounded-2xl font-bold text-sm shadow-lg flex items-center justify-center gap-2 transition-all"
              >
                {verifying ? <Loader2 className="animate-spin" size={16} /> : <Shield size={16} />}
                Verify Credential
              </button>
            </form>

            <AnimatePresence>
              {verifiedCert && (
                <motion.div
                  initial={{ opacity: 0, scale: 0.95 }}
                  animate={{ opacity: 1, scale: 1 }}
                  exit={{ opacity: 0, scale: 0.95 }}
                  className="p-5 bg-emerald-500/5 border border-emerald-500/10 rounded-2xl space-y-3 mt-4"
                >
                  <div className="flex items-center gap-2 text-emerald-400 text-sm font-bold">
                    <CheckCircle2 size={16} /> Authenticity Confirmed
                  </div>
                  <div className="text-xs space-y-2 font-medium text-slate-400">
                    <div>
                      <span className="text-slate-500 font-bold block uppercase tracking-wider text-[9px]">Recipient</span>
                      <strong className="text-slate-200">{verifiedCert.recipientName}</strong>
                    </div>
                    <div>
                      <span className="text-slate-500 font-bold block uppercase tracking-wider text-[9px]">Accreditation</span>
                      <strong className="text-slate-200">{verifiedCert.certificationName} ({verifiedCert.code})</strong>
                    </div>
                    <div>
                      <span className="text-slate-500 font-bold block uppercase tracking-wider text-[9px]">Status</span>
                      <strong className="text-emerald-400">{verifiedCert.status}</strong>
                    </div>
                    <div>
                      <span className="text-slate-500 font-bold block uppercase tracking-wider text-[9px]">Issuer</span>
                      <strong className="text-slate-200">{verifiedCert.issuingAuthority}</strong>
                    </div>
                  </div>
                </motion.div>
              )}
            </AnimatePresence>
          </div>
        </div>
      </div>

      {/* Exam Simulator Modal */}
      <AnimatePresence>
        {activeBooking && (
          <motion.div
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            exit={{ opacity: 0 }}
            className="fixed inset-0 bg-black/80 backdrop-blur-md z-[100] flex items-center justify-center p-4 overflow-y-auto"
          >
            <motion.div
              initial={{ scale: 0.95, y: 20 }}
              animate={{ scale: 1, y: 0 }}
              exit={{ scale: 0.95, y: 20 }}
              className="w-full max-w-[700px] glass border border-white/10 rounded-[2.5rem] p-8 md:p-12 shadow-2xl relative"
            >
              {!examResult ? (
                <form onSubmit={handleSubmitExam} className="space-y-8">
                  <div className="flex justify-between items-center border-b border-white/5 pb-4">
                    <h3 className="text-2xl font-bold flex items-center gap-2">
                      <HelpCircle className="text-primary" size={24} /> Assessment Portal
                    </h3>
                    <button
                      type="button"
                      onClick={() => setActiveBooking(null)}
                      className="text-slate-500 hover:text-white transition-colors"
                    >
                      <X size={24} />
                    </button>
                  </div>

                  <div className="space-y-6">
                    {currentQuestions.map((q, qIdx) => (
                      <div key={qIdx} className="space-y-3">
                        <h4 className="font-bold text-slate-200 text-sm leading-relaxed">
                          {qIdx + 1}. {q.questionText}
                        </h4>
                        <div className="grid grid-cols-1 gap-2.5">
                          {q.options.map((opt, oIdx) => {
                            const isSelected = currentAnswers[qIdx] === oIdx;
                            return (
                              <button
                                key={oIdx}
                                type="button"
                                onClick={() => handleAnswerSelect(qIdx, oIdx)}
                                className={`w-full text-left px-5 py-3 rounded-2xl text-xs font-semibold border transition-all ${isSelected ? 'bg-primary/20 border-primary text-white shadow-lg' : 'bg-slate-950 border-white/5 text-slate-400 hover:border-white/10 hover:text-slate-200'}`}
                              >
                                {opt}
                              </button>
                            );
                          })}
                        </div>
                      </div>
                    ))}
                  </div>

                  <div className="flex justify-end gap-4 border-t border-white/5 pt-6">
                    <button
                      type="button"
                      onClick={() => setActiveBooking(null)}
                      className="px-6 py-3 rounded-2xl font-bold text-sm text-slate-400 hover:bg-white/5 transition-all"
                    >
                      Cancel
                    </button>
                    <button
                      type="submit"
                      disabled={grading}
                      className="bg-primary hover:bg-primary-hover text-white px-8 py-3 rounded-2xl font-bold text-sm shadow-xl flex items-center gap-2 transition-all"
                    >
                      {grading ? <Loader2 className="animate-spin" size={16} /> : 'Submit Examination'}
                    </button>
                  </div>
                </form>
              ) : (
                <div className="text-center py-8 space-y-6">
                  <div className="mx-auto w-20 h-20 rounded-full flex items-center justify-center shadow-lg border-2">
                    {examResult.passed ? (
                      <Check className="text-emerald-400 animate-pulse" size={48} />
                    ) : (
                      <X className="text-rose-400" size={48} />
                    )}
                  </div>

                  <div className="space-y-2">
                    <h3 className="text-3xl font-extrabold tracking-tight">
                      {examResult.passed ? 'Assessment Passed!' : 'Assessment Incomplete'}
                    </h3>
                    <p className="text-slate-400 text-sm font-semibold">
                      Your achieved score is <strong className={examResult.passed ? 'text-emerald-400 text-lg' : 'text-rose-400 text-lg'}>{examResult.score}%</strong>
                    </p>
                  </div>

                  <p className="text-sm text-slate-400 font-medium max-w-md mx-auto leading-relaxed">
                    {examResult.message}
                  </p>

                  {examResult.passed && (
                    <div className="p-4 bg-emerald-500/5 border border-emerald-500/10 rounded-2xl max-w-sm mx-auto space-y-1">
                      <span className="text-[10px] font-bold text-slate-500 uppercase tracking-widest">Verification ID</span>
                      <code className="text-slate-200 font-bold block text-sm select-all">{examResult.qrCodeId}</code>
                    </div>
                  )}

                  <div className="pt-6">
                    <button
                      onClick={() => {
                        setActiveBooking(null);
                        fetchCertificationsAndProfile();
                      }}
                      className="bg-white/5 border border-white/10 hover:bg-primary hover:border-primary text-white px-8 py-3 rounded-2xl font-bold text-sm transition-all"
                    >
                      Close Portal
                    </button>
                  </div>
                </div>
              )}
            </motion.div>
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
};

export default Certifications;
